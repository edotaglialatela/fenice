"""Bridge between the GUI and the native ``fenice`` executable.

The C++ solver is the single source of truth for the available test cases and
their default parameters (``fenice --list-cases`` / ``--print-config``); the
GUI only collects parameters and launches the solver with them.
"""
from __future__ import annotations

import functools
import os
import subprocess
import tempfile

import fenice

ROOT_DIR = str(fenice.ROOT)


class SolverNotFound(RuntimeError):
    """Raised when the C++ solver has not been built."""


def solver_exe() -> str:
    """The solver executable (see fenice.exe: $FENICE_EXE, else build/release/fenice)."""
    try:
        return fenice.exe()
    except FileNotFoundError as e:
        raise SolverNotFound(str(e)) from None


def _run(*args: str) -> str:
    res = subprocess.run([solver_exe(), *args], capture_output=True, text=True)
    if res.returncode != 0:
        raise RuntimeError(f"fenice {' '.join(args)} failed:\n{res.stderr or res.stdout}")
    return res.stdout


@functools.lru_cache(maxsize=None)
def available_cases() -> tuple[str, ...]:
    """Registry keys of the built-in test cases, in registry order."""
    return tuple(line.strip() for line in _run("--list-cases").splitlines() if line.strip())


@functools.lru_cache(maxsize=None)
def case_defaults(name: str) -> dict[str, str]:
    """Fully resolved parameters (baseline + case DEFAULTS) for test case *name*, as strings."""
    out = _run("--case", name, "--print-config")
    return dict(line.split(" = ", 1) for line in out.splitlines() if " = " in line)


@functools.lru_cache(maxsize=None)
def case_explicit(name: str) -> frozenset:
    """The keys the case file itself sets (the rest are the solver's baseline)."""
    out = _run("--case", name, "--print-case-defaults")
    return frozenset(line.split(" = ", 1)[0].strip() for line in out.splitlines() if " = " in line)


# What the GUI starts the AMR fields at (a case that sets one of them keeps its own value): all three indicator variables, the refine and
# join thresholds at 0.11, a remesh at every step.
AMR_GUI_DEFAULTS = {"amr_indicator": "density+velocity+pressure", "amr_refine_threshold": "0.11", "amr_derefine_threshold": "0.11",
                    "amr_refine_every": "1"}


def amr_gui_defaults(name: str) -> dict[str, str]:
    """AMR_GUI_DEFAULTS without the keys the case sets itself."""
    try:
        explicit = case_explicit(name)
    except Exception:   # noqa: BLE001 - the solver is not available: the plain defaults
        explicit = frozenset()
    return {k: v for k, v in AMR_GUI_DEFAULTS.items() if k not in explicit}


def write_config(params: dict, path: str) -> None:
    """Write ``key = value`` lines (the solver's --config format)."""
    with open(path, "w", encoding="utf-8") as f:
        f.write("# Generated by the Fenice GUI\n")
        for key, value in params.items():
            f.write(f"{key} = {value}\n")


def save_case(params: dict, name: str) -> str:
    """Save the run described by *params* as a new case called *name* (``fenice --save-case``).

    The case is written to ``cases/<folder>/case.toml`` and the case list is refreshed.
    Returns the path of the written file; raises RuntimeError with the solver's message.
    """
    fd, cfg = tempfile.mkstemp(prefix="fenice_", suffix=".cfg")
    os.close(fd)
    try:
        write_config(params, cfg)
        out = _run("--config", cfg, "--save-case", name)
    finally:
        os.remove(cfg)
    available_cases.cache_clear()
    case_defaults.cache_clear()
    for line in out.splitlines():
        if line.startswith("[CASE] Wrote "):
            return line[len("[CASE] Wrote "):].split(" (from ")[0]
    return ""
